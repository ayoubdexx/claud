export function Icon({
  name,
  className,
  strokeWidth = 1.9,
}: {
  name: string;
  className?: string;
  strokeWidth?: number;
}) {
  const Component = registry[name] ?? Circle;
  return <Component className={className} strokeWidth={strokeWidth} aria-hidden />;
}

export function hasIcon(name: string) {
  return Boolean(registry[name]);
}
